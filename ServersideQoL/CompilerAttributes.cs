using System.ComponentModel;

namespace System.Runtime.CompilerServices
{
  [EditorBrowsable(EditorBrowsableState.Never)]
  public static class IsExternalInit;

  //
  // Summary:
  //     Indicates that compiler support for a particular feature is required for the
  //     location where this attribute is applied.
  [AttributeUsage(AttributeTargets.All, AllowMultiple = true, Inherited = false)]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public sealed class CompilerFeatureRequiredAttribute : Attribute
  {
    //
    // Summary:
    //     The System.Runtime.CompilerServices.CompilerFeatureRequiredAttribute.FeatureName
    //     used for the ref structs C# feature.
    public const string RefStructs = "RefStructs";
    //
    // Summary:
    //     The System.Runtime.CompilerServices.CompilerFeatureRequiredAttribute.FeatureName
    //     used for the required members C# feature.
    public const string RequiredMembers = "RequiredMembers";

    //
    // Summary:
    //     Initializes a System.Runtime.CompilerServices.CompilerFeatureRequiredAttribute
    //     instance for the passed in compiler feature.
    //
    // Parameters:
    //   featureName:
    //     The name of the required compiler feature.
    public CompilerFeatureRequiredAttribute(string featureName) => FeatureName = featureName;

    //
    // Summary:
    //     The name of the compiler feature.
    public string FeatureName { get; }
    //
    // Summary:
    //     Gets a value that indicates whether the compiler can choose to allow access to
    //     the location where this attribute is applied if it does not understand System.Runtime.CompilerServices.CompilerFeatureRequiredAttribute.FeatureName.
    //
    //
    // Returns:
    //     true to let the compiler choose to allow access to the location where this attribute
    //     is applied if it does not understand System.Runtime.CompilerServices.CompilerFeatureRequiredAttribute.FeatureName;
    //     otherwise, false.
    public bool IsOptional { get; init; }
  }

  //
  // Summary:
  //     Specifies that a type has required members or that a member is required.
  [AttributeUsage(AttributeTargets.Class | AttributeTargets.Struct | AttributeTargets.Property | AttributeTargets.Field, AllowMultiple = false, Inherited = false)]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public sealed class RequiredMemberAttribute : Attribute;

  /// <summary>
  /// Reserved for use by a compiler for tracking metadata.
  /// This attribute should not be used by developers in source code.
  /// </summary>
  [EditorBrowsable(EditorBrowsableState.Never)]
  [AttributeUsage(AttributeTargets.Class, Inherited = false)]
  public sealed class IsClosedTypeAttribute : Attribute
  {
    private Type[] _derivedTypes = Type.EmptyTypes;

    /// <summary>Initializes the attribute.</summary>
    public IsClosedTypeAttribute()
    {
    }

    /// <summary>Gets or sets the derived types of the closed type.</summary>
    /// <value>An array of the derived types of the closed type. A <see langword="null" /> value is normalized to an empty array.</value>
    public Type[] DerivedTypes
    {
      get => _derivedTypes;
      set => _derivedTypes = value ?? Type.EmptyTypes;
    }
  }

  /// <summary>
  /// Indicates that a class or struct is a union type, enabling compiler support for union behaviors.
  /// </summary>
  /// <remarks>
  /// <para>
  /// Any class or struct annotated with this attribute is recognized by the C# compiler as a union type.
  /// Union types may support behaviors such as implicit conversions from case types, pattern matching
  /// that unwraps the union's contents, and switch exhaustiveness checking.
  /// </para>
  /// </remarks>
  /// <seealso cref="IUnion" />
  [AttributeUsage(AttributeTargets.Class | AttributeTargets.Struct, AllowMultiple = false, Inherited = false)]
  public sealed class UnionAttribute : Attribute
  {
  }

  /// <summary>
  /// Provides a common interface for accessing the contents of a union type at runtime.
  /// </summary>
  /// <remarks>
  /// <para>
  /// The C# compiler automatically implements this interface on types generated by union declarations.
  /// User-defined types annotated with <see cref="UnionAttribute" /> may also implement this interface
  /// to provide runtime access to the union's value. Implementing this interface is not required
  /// for union behaviors provided by the compiler.
  /// </para>
  /// </remarks>
  /// <seealso cref="UnionAttribute" />
  public interface IUnion
  {
    /// <summary>
    /// Gets the value contained in the union, or <see langword="null" /> if the union has no value.
    /// </summary>
    /// <value>
    /// The current value of the union as one of its case types, or <see langword="null" />.
    /// </value>
    object? Value { get; }
  }
}

namespace System.Diagnostics.CodeAnalysis
{
  //
  // Summary:
  //     Specifies that this constructor sets all required members for the current type,
  //     and callers do not need to set any required members themselves.
  [AttributeUsage(AttributeTargets.Constructor, AllowMultiple = false, Inherited = false)]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public sealed class SetsRequiredMembersAttribute : Attribute;

  //
  // Summary:
  //     Specifies that the method or property will ensure that the listed field and property
  //     members have values that aren't null.
  [AttributeUsage(AttributeTargets.Method | AttributeTargets.Property, Inherited = false, AllowMultiple = true)]
  public sealed class MemberNotNullAttribute : Attribute
  {
    //
    // Summary:
    //     Initializes the attribute with a field or property member.
    //
    // Parameters:
    //   member:
    //     The field or property member that is promised to be non-null.
    public MemberNotNullAttribute(string member) => Members = [member];
    //
    // Summary:
    //     Initializes the attribute with the list of field and property members.
    //
    // Parameters:
    //   members:
    //     The list of field and property members that are promised to be non-null.
    public MemberNotNullAttribute(params string[] members) => Members = members;

    //
    // Summary:
    //     Gets field or property member names.
    public string[] Members { get; }
  }

  //
  // Summary:
  //     Specifies that the method or property will ensure that the listed field and property
  //     members have non-null values when returning with the specified return value condition.
  [AttributeUsage(AttributeTargets.Method | AttributeTargets.Property, Inherited = false, AllowMultiple = true)]
  public sealed class MemberNotNullWhenAttribute : Attribute
  {
    //
    // Summary:
    //     Initializes the attribute with the specified return value condition and a field
    //     or property member.
    //
    // Parameters:
    //   returnValue:
    //     The return value condition. If the method returns this value, the associated
    //     parameter will not be null.
    //
    //   member:
    //     The field or property member that is promised to be non-null.
    public MemberNotNullWhenAttribute(bool returnValue, string member)
    {
      ReturnValue = returnValue;
      Members = [member];
    }
    //
    // Summary:
    //     Initializes the attribute with the specified return value condition and list
    //     of field and property members.
    //
    // Parameters:
    //   returnValue:
    //     The return value condition. If the method returns this value, the associated
    //     parameter will not be null.
    //
    //   members:
    //     The list of field and property members that are promised to be non-null.
    public MemberNotNullWhenAttribute(bool returnValue, params string[] members)
    {
      ReturnValue = returnValue;
      Members = members;
    }

    //
    // Summary:
    //     Gets field or property member names.
    public string[] Members { get; }
    //
    // Summary:
    //     Gets the return value condition.
    public bool ReturnValue { get; }
  }
}
