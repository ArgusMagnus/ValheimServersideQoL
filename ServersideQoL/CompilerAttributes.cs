using System.ComponentModel;

namespace System.Runtime.CompilerServices
{
  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/IsExternalInit.cs
  /// <summary>
  /// Reserved to be used by the compiler for tracking metadata.
  /// This class should not be used by developers in source code.
  /// </summary>
  [EditorBrowsable(EditorBrowsableState.Never)]
  public static class IsExternalInit;

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/CompilerFeatureRequiredAttribute.cs
  /// <summary>
  /// Indicates that compiler support for a particular feature is required for the location where this attribute is applied.
  /// </summary>
  [AttributeUsage(AttributeTargets.All, AllowMultiple = true, Inherited = false)]
  public sealed class CompilerFeatureRequiredAttribute : Attribute
  {
    public CompilerFeatureRequiredAttribute(string featureName)
    {
      FeatureName = featureName;
    }

    /// <summary>
    /// The name of the compiler feature.
    /// </summary>
    public string FeatureName { get; }

    /// <summary>
    /// If true, the compiler can choose to allow access to the location where this attribute is applied if it does not understand <see cref="FeatureName"/>.
    /// </summary>
    public bool IsOptional { get; init; }

    /// <summary>
    /// The <see cref="FeatureName"/> used for the ref structs C# feature.
    /// </summary>
    public const string RefStructs = nameof(RefStructs);

    /// <summary>
    /// The <see cref="FeatureName"/> used for the required members C# feature.
    /// </summary>
    public const string RequiredMembers = nameof(RequiredMembers);
  }

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/RequiredMemberAttribute.cs
  /// <summary>Specifies that a type has required members or that a member is required.</summary>
  [AttributeUsage(AttributeTargets.Class | AttributeTargets.Struct | AttributeTargets.Field | AttributeTargets.Property, AllowMultiple = false, Inherited = false)]
  [EditorBrowsable(EditorBrowsableState.Never)]
  public sealed class RequiredMemberAttribute : Attribute;

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/IsClosedTypeAttribute.cs
  /// <summary>
  /// Reserved for use by a compiler for tracking metadata.
  /// This attribute should not be used by developers in source code.
  /// </summary>
  [EditorBrowsable(EditorBrowsableState.Never)]
  [AttributeUsage(AttributeTargets.Class, Inherited = false)]
  public sealed class IsClosedTypeAttribute : Attribute
  {
    private Type[] _derivedTypes = Type.EmptyTypes;

    /// <summary>Initializes the attribute.</summary>
    public IsClosedTypeAttribute()
    {
    }

    /// <summary>Gets or sets the derived types of the closed type.</summary>
    /// <value>An array of the derived types of the closed type. A <see langword="null" /> value is normalized to an empty array.</value>
    public Type[] DerivedTypes
    {
      get => _derivedTypes;
      set => _derivedTypes = value ?? Type.EmptyTypes;
    }
  }

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/UnionAttribute.cs
  /// <summary>
  /// Indicates that a class or struct is a union type, enabling compiler support for union behaviors.
  /// </summary>
  /// <remarks>
  /// <para>
  /// Any class or struct annotated with this attribute is recognized by the C# compiler as a union type.
  /// Union types may support behaviors such as implicit conversions from case types, pattern matching
  /// that unwraps the union's contents, and switch exhaustiveness checking.
  /// </para>
  /// </remarks>
  /// <seealso cref="IUnion" />
  [AttributeUsage(AttributeTargets.Class | AttributeTargets.Struct, AllowMultiple = false, Inherited = false)]
  public sealed class UnionAttribute : Attribute;

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Runtime/CompilerServices/IUnion.cs
  /// <summary>
  /// Provides a common interface for accessing the contents of a union type at runtime.
  /// </summary>
  /// <remarks>
  /// <para>
  /// The C# compiler automatically implements this interface on types generated by union declarations.
  /// User-defined types annotated with <see cref="UnionAttribute" /> may also implement this interface
  /// to provide runtime access to the union's value. Implementing this interface is not required
  /// for union behaviors provided by the compiler.
  /// </para>
  /// </remarks>
  /// <seealso cref="UnionAttribute" />
  public interface IUnion
  {
    /// <summary>
    /// Gets the value contained in the union, or <see langword="null" /> if the union has no value.
    /// </summary>
    /// <value>
    /// The current value of the union as one of its case types, or <see langword="null" />.
    /// </value>
    object? Value { get; }
  }
}

namespace System.Diagnostics.CodeAnalysis
{
  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Diagnostics/CodeAnalysis/SetsRequiredMembersAttribute.cs
  /// <summary>
  /// Specifies that this constructor sets all required members for the current type, and callers
  /// do not need to set any required members themselves.
  /// </summary>
  [AttributeUsage(AttributeTargets.Constructor, AllowMultiple = false, Inherited = false)]
  public sealed class SetsRequiredMembersAttribute : Attribute;

  // https://github.com/dotnet/dotnet/blob/main/src/runtime/src/libraries/System.Private.CoreLib/src/System/Diagnostics/CodeAnalysis/NullableAttributes.cs
  /// <summary>Specifies that null is allowed as an input even if the corresponding type disallows it.</summary>
  [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter | AttributeTargets.Property, Inherited = false)]
  public sealed class AllowNullAttribute : Attribute;

  /// <summary>Specifies that null is disallowed as an input even if the corresponding type allows it.</summary>
  [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter | AttributeTargets.Property, Inherited = false)]
  public sealed class DisallowNullAttribute : Attribute;

  /// <summary>Specifies that an output may be null even if the corresponding type disallows it.</summary>
  [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter | AttributeTargets.Property | AttributeTargets.ReturnValue, Inherited = false)]
  public sealed class MaybeNullAttribute : Attribute;

  /// <summary>Specifies that an output will not be null even if the corresponding type allows it. Specifies that an input argument was not null when the call returns.</summary>
  [AttributeUsage(AttributeTargets.Field | AttributeTargets.Parameter | AttributeTargets.Property | AttributeTargets.ReturnValue, Inherited = false)]
  public sealed class NotNullAttribute : Attribute;

  /// <summary>Specifies that when a method returns <see cref="ReturnValue"/>, the parameter may be null even if the corresponding type disallows it.</summary>
  [AttributeUsage(AttributeTargets.Parameter, Inherited = false)]
  public sealed class MaybeNullWhenAttribute : Attribute
  {
    /// <summary>Initializes the attribute with the specified return value condition.</summary>
    /// <param name="returnValue">
    /// The return value condition. If the method returns this value, the associated parameter may be null.
    /// </param>
    public MaybeNullWhenAttribute(bool returnValue) => ReturnValue = returnValue;

    /// <summary>Gets the return value condition.</summary>
    public bool ReturnValue { get; }
  }

  /// <summary>Specifies that when a method returns <see cref="ReturnValue"/>, the parameter will not be null even if the corresponding type allows it.</summary>
  [AttributeUsage(AttributeTargets.Parameter, Inherited = false)]
  public sealed class NotNullWhenAttribute : Attribute
  {
    /// <summary>Initializes the attribute with the specified return value condition.</summary>
    /// <param name="returnValue">
    /// The return value condition. If the method returns this value, the associated parameter will not be null.
    /// </param>
    public NotNullWhenAttribute(bool returnValue) => ReturnValue = returnValue;

    /// <summary>Gets the return value condition.</summary>
    public bool ReturnValue { get; }
  }

  /// <summary>Specifies that the output will be non-null if the named parameter is non-null.</summary>
  [AttributeUsage(AttributeTargets.Parameter | AttributeTargets.Property | AttributeTargets.ReturnValue, AllowMultiple = true, Inherited = false)]
  public sealed class NotNullIfNotNullAttribute : Attribute
  {
    /// <summary>Initializes the attribute with the associated parameter name.</summary>
    /// <param name="parameterName">
    /// The associated parameter name.  The output will be non-null if the argument to the parameter specified is non-null.
    /// </param>
    public NotNullIfNotNullAttribute(string parameterName) => ParameterName = parameterName;

    /// <summary>Gets the associated parameter name.</summary>
    public string ParameterName { get; }
  }

  /// <summary>Applied to a method that will never return under any circumstance.</summary>
  [AttributeUsage(AttributeTargets.Method, Inherited = false)]
  public sealed class DoesNotReturnAttribute : Attribute;

  /// <summary>Specifies that the method will not return if the associated Boolean parameter is passed the specified value.</summary>
  [AttributeUsage(AttributeTargets.Parameter, Inherited = false)]
  public sealed class DoesNotReturnIfAttribute : Attribute
  {
    /// <summary>Initializes the attribute with the specified parameter value.</summary>
    /// <param name="parameterValue">
    /// The condition parameter value. Code after the method will be considered unreachable by diagnostics if the argument to
    /// the associated parameter matches this value.
    /// </param>
    public DoesNotReturnIfAttribute(bool parameterValue) => ParameterValue = parameterValue;

    /// <summary>Gets the condition parameter value.</summary>
    public bool ParameterValue { get; }
  }

  /// <summary>Specifies that the method or property will ensure that the listed field and property members have not-null values.</summary>
  [AttributeUsage(AttributeTargets.Method | AttributeTargets.Property, Inherited = false, AllowMultiple = true)]
  public sealed class MemberNotNullAttribute : Attribute
  {
    /// <summary>Initializes the attribute with a field or property member.</summary>
    /// <param name="member">
    /// The field or property member that is promised to be not-null.
    /// </param>
    public MemberNotNullAttribute(string member) => Members = [member];

    /// <summary>Initializes the attribute with the list of field and property members.</summary>
    /// <param name="members">
    /// The list of field and property members that are promised to be not-null.
    /// </param>
    public MemberNotNullAttribute(params string[] members) => Members = members;

    /// <summary>Gets field or property member names.</summary>
    public string[] Members { get; }
  }

  /// <summary>Specifies that the method or property will ensure that the listed field and property members have not-null values when returning with the specified return value condition.</summary>
  [AttributeUsage(AttributeTargets.Method | AttributeTargets.Property, Inherited = false, AllowMultiple = true)]
  public sealed class MemberNotNullWhenAttribute : Attribute
  {
    /// <summary>Initializes the attribute with the specified return value condition and a field or property member.</summary>
    /// <param name="returnValue">
    /// The return value condition. If the method returns this value, the associated field or property member will not be null.
    /// </param>
    /// <param name="member">
    /// The field or property member that is promised to be not-null.
    /// </param>
    public MemberNotNullWhenAttribute(bool returnValue, string member)
    {
      ReturnValue = returnValue;
      Members = [member];
    }

    /// <summary>Initializes the attribute with the specified return value condition and list of field and property members.</summary>
    /// <param name="returnValue">
    /// The return value condition. If the method returns this value, the associated field and property members will not be null.
    /// </param>
    /// <param name="members">
    /// The list of field and property members that are promised to be not-null.
    /// </param>
    public MemberNotNullWhenAttribute(bool returnValue, params string[] members)
    {
      ReturnValue = returnValue;
      Members = members;
    }

    /// <summary>Gets the return value condition.</summary>
    public bool ReturnValue { get; }

    /// <summary>Gets field or property member names.</summary>
    public string[] Members { get; }
  }
}
